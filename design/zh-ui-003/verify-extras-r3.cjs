const {chromium}=require(process.env.ZHIJI_PW||'playwright')
const assert=require('node:assert/strict')
async function run(){
  const browser=await chromium.launch({channel:'msedge'})
  try {
    const p=await browser.newPage({viewport:{width:390,height:844}})
    p.setDefaultTimeout(4000)
    await p.goto('http://127.0.0.1:18403/#clip')
    const click=s=>p.locator(s).first().click()
    assert.equal(await p.locator('.ex-open').count(),34)
    await p.locator('.ex-fallback').first().waitFor()
    await click('[data-x=layout]')
    await click('[data-file="10"]')
    await p.locator('.ex-inspect').waitFor()
    await click('[data-x=dismiss]')
    await click('[data-x=batch]')
    await click('[data-file="4"]')
    await click('[data-file="5"]')
    assert.equal(await p.locator('.ex-file.is-selected').count(),2)
    p.once('dialog',d=>d.accept())
    await click('[data-x=act]')
    assert.equal(await p.locator('.ex-open').count(),32)
    await p.evaluate(()=>R2Extras.openTrash())
    assert.equal(await p.locator('.ex-open').count(),3)
    await click('[data-file="4"]')
    await p.locator('.ex-inspect summary').click()
    await click('[data-x="recover-4"]')
    await click('[data-file="5"]')
    await p.locator('.ex-inspect summary').click()
    p.once('dialog',d=>d.dismiss())
    await click('[data-x=purgeOne]')
    assert.equal(await p.locator('.ex-open').count(),2)
    if(!await p.locator('[data-x=purgeOne]').isVisible())await p.locator('.ex-inspect summary').click()
    p.once('dialog',d=>d.accept())
    await click('[data-x=purgeOne]')
    assert.equal(await p.locator('.ex-open').count(),1)
    await click('[data-nav=check]')
    assert.equal(await p.locator('.ex-task').count(),24)
    const edit=p.locator('[data-x="edit-1"]')
    await edit.focus()
    await edit.press('Enter')
    await p.locator('[data-task-form]').waitFor()
    assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    console.log('PASS: 390px / 34 files, fallback, list, selection, batch trash, recovery, purge confirm/cancel, 24 tasks and keyboard edit')
  }finally{await browser.close()}
}
run().catch(error=>{console.error(error);process.exitCode=1})
