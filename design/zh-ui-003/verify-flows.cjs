const assert=require('node:assert/strict')
const {chromium}=require(process.env.ZHIJI_PW||'playwright')
async function run(){
 const browser=await chromium.launch({channel:'msedge'})
 try {
  const page=await browser.newPage({viewport:{width:1440,height:900}})
  page.setDefaultTimeout(4000)
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  const click=s=>page.locator(s).first().click()
  await page.goto('http://127.0.0.1:18403/')
  const search=page.locator('#search')
  await search.fill('无匹配-验收测试')
  assert.equal(await page.locator('#notes .note').count(),0)
  await search.fill('')
  assert.ok(await page.locator('#notes .note').count()>=20)
  await click('[data-cmd=filters]')
  await click('.range-trigger')
  await click('.range-panel:popover-open [data-day]')
  assert.ok(await page.locator('.range-panel:popover-open').count())
  await page.keyboard.press('Escape')
  await click('[data-cmd=calendar]')
  await click('.month-grid [data-day="2026-11-17"]')
  await click('[data-cmd=compose]')
  assert.equal(await page.locator('[name=date]').inputValue(),'2026-11-17')
  await page.locator('[name=title]').fill('验收草稿')
  await page.locator('[name=body]').fill('第一段草稿')
  page.once('dialog',d=>d.dismiss())
  await click('[data-nav=clip]')
  assert.equal(await page.locator('[name=body]').inputValue(),'第一段草稿')
  await click('.editor-doc button[type=submit]')
  assert.equal(await page.locator('.reader-body h2').innerText(),'验收草稿')
  await click('[data-nav=clip]')
  await click('[data-file="3"]')
  assert.equal(await page.locator('video').count(),1)
  await page.locator('video').evaluate(async v=>{await v.play();v.pause()})
  await click('[data-nav=check]')
  assert.ok(await page.locator('.ex-task').count()>=20)
  await click('[data-x="edit-0"]')
  await page.locator('[data-task-form] input[name=title]').fill('修改后的示例任务')
  await click('[data-task-form] button[type=submit]')
  await page.getByText('修改后的示例任务',{exact:true}).waitFor()
  await click('[data-x=undo]')
  assert.equal(await page.getByText('修改后的示例任务',{exact:true}).count(),0)
  await click('[data-nav=settings]')
  await click('[data-pref="回收站"]')
  await page.getByRole('switch').check()
  assert.ok(await page.getByRole('switch').isChecked())
  assert.deepEqual(errors,[])
  console.log('PASS empty/search, actual range cancellation, calendar-to-compose, draft protection/save, video playback, 24-task edit/undo, settings switch')
 }finally{await browser.close()}
}
run().catch(e=>{console.error(e);process.exitCode=1})
