/* Run only against a newly created disposable backend with a built frontend. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.ZHIJI_PW || 'playwright')

async function run() {
  const origin = process.env.ZHIJI_PAGINATION_TEST_ORIGIN
  assert.match(origin || '', /^http:\/\/127\.0\.0\.1:\d+$/)
  const browser = await chromium.launch({ channel: 'msedge' })
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 900}})
    page.setDefaultTimeout(5000)
    const status = await (await page.request.get(origin + '/api/auth/status')).json()
    assert.equal(status.needs_setup, true, 'Requires a fresh isolated database')
    const pass = 'disposable-pagination-test'
    const button = name => page.getByRole('button', {name, exact: true}).first()
    const title = page.locator('.note-detail-title')
    const heading = text => page.getByRole('heading', {name: text, exact: true}).waitFor()
    const api = async (path, method, data) => {
      const response = await page.request.fetch(origin + path, {method, data, headers: {Origin: origin}})
      assert.ok(response.ok(), await response.text())
      return response.json()
    }
    await api('/api/auth/setup', 'POST', {password: pass})
    const records = []
    for (let i = 1; i <= 111; i++) {
      const result = await api('/api/records', 'POST', {title: '分页验证 ' + i, content: '测试正文 ' + i})
      records.push(result.record)
    }
    await page.goto(origin)
    await heading('分页验证 111')
    const idle = () => page.locator('.library-scroll-region[aria-busy=false]').waitFor()
    const turn = async () => { await button('下一页').click(); await idle() }
    const expectPage = async number => assert.match(await page.locator('.record-pagination span').innerText(), new RegExp('第 ' + number + ' /'))
    const roundtrip = async expected => {
      await page.locator('.nav-item[aria-label="收集箱"]').click()
      await idle()
      await page.locator('.nav-item[aria-label="我的知识库"]').click()
      await heading(expected)
      await button(expected).waitFor()
    }
    await turn()
    await button('分页验证 84').click()
    await roundtrip('分页验证 84')
    await expectPage(2)
    console.log('PASS page 2 navigation')
    await turn()
    await button('分页验证 61').click()
    await roundtrip('分页验证 61')
    await expectPage(3)
    await page.reload()
    await heading('分页验证 61')
    await button('退出登录').click()
    await page.locator('input[type=password]').fill(pass)
    await button('登录').click()
    await heading('分页验证 61')
    console.log('PASS page 3 navigation, refresh and login')
    await page.getByRole('searchbox',{name:'搜索知识库'}).fill('分页验证 10')
    await button('搜索').click()
    await button('分页验证 101').click()
    await heading('分页验证 101')
    await button('清除搜索').click()
    await heading('分页验证 61')
    await page.reload()
    await heading('分页验证 61')
    console.log('PASS temporary search does not replace reading history')
    await page.getByLabel('记录排序').selectOption('oldest')
    await button('分页验证 3').click()
    await heading('分页验证 3')
    await page.getByLabel('记录排序').selectOption('newest')
    await heading('分页验证 61')
    await expectPage(3)
    await page.locator('.nav-item[aria-label="收集箱"]').click()
    await idle()
    await turn()
    await button('分页验证 83').click()
    await roundtrip('分页验证 61')
    await page.locator('.nav-item[aria-label="收集箱"]').click()
    await heading('分页验证 83')
    await expectPage(2)
    await page.locator('.nav-item[aria-label="我的知识库"]').click()
    await heading('分页验证 61')
    console.log('PASS temporary sort and independent inbox page')
    // Removing a newer record moves the bookmarked first row of page 3 onto page 2.
    await api('/api/records/' + records[110].id, 'DELETE')
    await page.reload()
    await heading('分页验证 61')
    await button('分页验证 61').waitFor()
    await expectPage(2)
    await api('/api/records/' + records[60].id, 'DELETE')
    await page.reload()
    await title.waitFor()
    const fallback = await title.innerText()
    assert.notEqual(fallback,'分页验证 61')
    await button(fallback).waitFor()
    await page.reload()
    await heading(fallback)
    console.log('PASS shifted rank and deleted bookmark fallback:', fallback)
  } finally { await browser.close() }
}
run().catch(error => {console.error(error); process.exitCode = 1})
